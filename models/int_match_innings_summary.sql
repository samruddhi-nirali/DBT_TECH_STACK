SELECT
    MATCH_ID,
    INNINGS_NUMBER,
    MAX(BATTING_TEAM) AS BATTING_TEAM,

    COUNT(*) AS DELIVERY_RECORDS,

    SUM(COALESCE(BATTER_RUNS, 0)) AS BATTER_RUNS,
    SUM(COALESCE(EXTRAS_RUNS, 0)) AS EXTRAS_RUNS,
    SUM(COALESCE(TOTAL_RUNS, 0)) AS TOTAL_RUNS,

    SUM(COALESCE(WICKET_COUNT, 0)) AS WICKETS,

    COUNT(DISTINCT OVER_NUMBER) AS OVERS_WITH_DELIVERIES

FROM {{ ref('stg_deliveries') }}

GROUP BY
    MATCH_ID,
    INNINGS_NUMBER
