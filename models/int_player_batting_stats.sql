SELECT
    MATCH_ID,
    INNINGS_NUMBER,
    BATTING_TEAM,
    BATTER,
    SUM(COALESCE(BATTER_RUNS,0)) AS RUNS_SCORED,
    COUNT_IF(COALESCE(EXTRAS_RUNS,0)=0) AS BALLS_FACED,
    COUNT_IF(COALESCE(BATTER_RUNS,0)=4) AS FOURS,
    COUNT_IF(COALESCE(BATTER_RUNS,0)=6) AS SIXES,
    ROUND(100.0 * SUM(COALESCE(BATTER_RUNS,0))/ NULLIF(COUNT_IF(COALESCE(EXTRAS_RUNS,0)=0),0),2) AS STRIKE_RATE
FROM {{ref("stg_deliveries")}}
group by all